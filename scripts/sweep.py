#!/usr/bin/env python3
"""Regression sweep: run svgm (new and, optionally, a baseline build) and svgo
over a corpus and report hangs, panics, empty outputs, non-idempotent output,
byte changes vs the baseline and, with --render, pixel changes.

Corpora:
  empirical  input half of every SVGO plugin fixture (SVGO_DIR/test/plugins/
             *.svg.txt), every svgm test fixture, and BENCH_DIR/*.svg
  malformed  generated by scripts/gen_malformed.py

Typical use (baseline = the last release tag):
  git archive v0.4.0 | tar -x -C /tmp/svgm-0.4.0 && (cd /tmp/svgm-0.4.0 && cargo build --release)
  cargo build --release
  scripts/sweep.py --corpus empirical --old /tmp/svgm-0.4.0/target/release/svgm --out /tmp/sweep-e --render
  scripts/sweep.py --corpus malformed --old /tmp/svgm-0.4.0/target/release/svgm --out /tmp/sweep-m

Exit status is 1 when the new binary hangs, panics, produces empty output
for a parseable input, is not idempotent, or (with --render) renders any
changed file differently from the baseline.
"""
import argparse
import concurrent.futures as cf
import glob
import os
import shutil
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def run_svgm(binary, path, timeout):
    """Return (status, stdout bytes, stderr text)."""
    try:
        p = subprocess.run(
            [binary, path, "--stdout", "--no-config"],
            capture_output=True,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        return "HANG", b"", ""
    err = p.stderr.decode("utf-8", "replace")
    # The CLI catches panics and reports them as "internal error".
    if "panicked" in err or "internal error" in err or p.returncode < 0 or p.returncode == 101:
        return "PANIC", p.stdout, err.strip().splitlines()[0][:200] if err.strip() else ""
    if p.returncode != 0:
        return "ERR", p.stdout, err.strip().replace("\n", " | ")[:200]
    if not p.stdout.strip():
        return "EMPTY", p.stdout, err
    return "OK", p.stdout, err


def run_svgo(path, timeout):
    if not shutil.which("svgo"):
        return None
    try:
        p = subprocess.run(["svgo", "-i", path, "-o", "-"], capture_output=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return None
    return p.stdout if p.returncode == 0 else None


def build_empirical(inp, svgo_dir, bench_dir):
    n = 0
    for f in sorted(glob.glob(os.path.join(svgo_dir, "test/plugins/*.svg.txt"))):
        name = os.path.basename(f)[: -len(".svg.txt")]
        text = open(f, encoding="utf-8").read()
        # Optional description, then "===", then input, "@@@", expected
        # output and optionally "@@@" + plugin params.
        if "\n===\n" in text:
            text = text.split("\n===\n", 1)[1]
        text = text.split("\n@@@")[0].strip()
        open(os.path.join(inp, f"svgo__{name}.svg"), "w", encoding="utf-8").write(text + "\n")
        n += 1
    fixtures = os.path.join(REPO, "crates/svgm-core/tests/fixtures")
    for f in sorted(glob.glob(os.path.join(fixtures, "**/*.svg"), recursive=True)):
        rel = os.path.relpath(f, fixtures).replace(os.sep, "_")
        shutil.copyfile(f, os.path.join(inp, f"svgm__{rel}"))
        n += 1
    for f in sorted(glob.glob(os.path.join(bench_dir, "*.svg"))):
        shutil.copyfile(f, os.path.join(inp, f"bench__{os.path.basename(f)}"))
        n += 1
    return n


def render(svg_bytes, png_path):
    """Rasterise with rsvg-convert; return PNG bytes or None."""
    try:
        p = subprocess.run(
            ["rsvg-convert", "-w", "256", "-f", "png"],
            input=svg_bytes,
            capture_output=True,
            timeout=30,
        )
    except subprocess.TimeoutExpired:
        return None
    if p.returncode != 0:
        return None
    open(png_path, "wb").write(p.stdout)
    return p.stdout


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--corpus", choices=["empirical", "malformed"], required=True)
    ap.add_argument("--new", default=os.path.join(REPO, "target/release/svgm"))
    ap.add_argument("--old", help="baseline svgm binary (e.g. built from the last tag)")
    ap.add_argument("--out", required=True, help="scratch directory (recreated)")
    ap.add_argument("--svgo-dir", default=os.path.expanduser("~/svgo"))
    ap.add_argument("--bench-dir", default=os.path.expanduser("~/Desktop/svg-logos-benchmark-test"))
    ap.add_argument("--no-svgo", action="store_true", help="skip running svgo")
    ap.add_argument("--render", action="store_true", help="pixel-compare old vs new for changed files")
    ap.add_argument("--timeout", type=int, default=15)
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    args = ap.parse_args()

    if os.path.exists(args.out):
        shutil.rmtree(args.out)
    inp = os.path.join(args.out, "in")
    outs = {k: os.path.join(args.out, k) for k in ("new", "old", "svgo", "png")}
    os.makedirs(inp)
    for d in outs.values():
        os.makedirs(d)

    if args.corpus == "empirical":
        count = build_empirical(inp, args.svgo_dir, args.bench_dir)
    else:
        subprocess.run([sys.executable, os.path.join(REPO, "scripts/gen_malformed.py"), inp], check=True)
        count = len(os.listdir(inp))
    print(f"{count} inputs in {inp}")
    run_svgo_too = not args.no_svgo and args.corpus == "empirical"

    def one(name):
        path = os.path.join(inp, name)
        row = {"name": name, "in": os.path.getsize(path)}
        status, out, err = run_svgm(args.new, path, args.timeout)
        row.update(status=status, new=len(out), err=err)
        open(os.path.join(outs["new"], name), "wb").write(out)
        if status == "OK":
            tmp = os.path.join(outs["new"], name + ".pass1.svg")
            open(tmp, "wb").write(out)
            s2, out2, _ = run_svgm(args.new, tmp, args.timeout)
            os.remove(tmp)
            row["idempotent"] = s2 == "OK" and out2 == out
        else:
            row["idempotent"] = True
        if args.old:
            s_old, out_old, _ = run_svgm(args.old, path, args.timeout)
            row.update(old_status=s_old, old=len(out_old), changed=out_old != out)
            open(os.path.join(outs["old"], name), "wb").write(out_old)
        if run_svgo_too:
            so = run_svgo(path, args.timeout * 2)
            row["svgo"] = len(so) if so is not None else -1
            if so is not None:
                open(os.path.join(outs["svgo"], name), "wb").write(so)
        if args.render and args.old and row.get("changed") and status == "OK" and row["old_status"] == "OK":
            base = os.path.join(outs["png"], name)
            a = render(open(os.path.join(outs["old"], name), "rb").read(), base + ".old.png")
            b = render(out, base + ".new.png")
            row["pixels"] = "n/a" if a is None or b is None else ("same" if a == b else "DIFF")
        return row

    with cf.ThreadPoolExecutor(args.jobs) as ex:
        rows = sorted(ex.map(one, sorted(os.listdir(inp))), key=lambda r: r["name"])

    cols = ["name", "in", "status", "new", "idempotent", "old_status", "old", "changed", "svgo", "pixels", "err"]
    with open(os.path.join(args.out, "results.tsv"), "w") as f:
        f.write("\t".join(cols) + "\n")
        for r in rows:
            f.write("\t".join(str(r.get(c, "")) for c in cols) + "\n")

    bad = []
    for r in rows:
        if r["status"] in ("HANG", "PANIC"):
            bad.append(f"{r['status']}: {r['name']} {r['err']}")
        elif r["status"] == "EMPTY":
            bad.append(f"EMPTY: {r['name']}")
        elif not r["idempotent"]:
            bad.append(f"NOT IDEMPOTENT: {r['name']}")
        if r.get("pixels") == "DIFF":
            bad.append(f"PIXEL DIFF vs old: {r['name']}")
        if args.old and r.get("old_status") == "OK" and r["status"] != "OK":
            bad.append(f"REGRESSED to {r['status']}: {r['name']}")

    ok = [r for r in rows if r["status"] == "OK"]
    print(f"status: " + ", ".join(f"{s}={sum(r['status'] == s for r in rows)}" for s in ("OK", "ERR", "EMPTY", "PANIC", "HANG")))
    print(f"idempotent: {sum(r['idempotent'] for r in ok)}/{len(ok)}")
    if args.old:
        changed = [r for r in rows if r.get("changed")]
        smaller = sum(r["new"] < r["old"] for r in changed)
        larger = [r for r in changed if r["new"] > r["old"]]
        delta = sum(r["new"] - r["old"] for r in changed)
        print(f"changed vs old: {len(changed)} (smaller {smaller}, larger {len(larger)}, same size {len(changed) - smaller - len(larger)}), total delta {delta:+d} bytes")
        for r in changed:
            print(f"  {r['new'] - r['old']:+6d}  {r['name']}  pixels={r.get('pixels', '-')}")
    if run_svgo_too:
        both = [r for r in ok if r.get("svgo", -1) >= 0]
        print(f"vs svgo: svgm {sum(r['new'] for r in both)} B, svgo {sum(r['svgo'] for r in both)} B over {len(both)} files; svgm smaller on {sum(r['new'] < r['svgo'] for r in both)}, larger on {sum(r['new'] > r['svgo'] for r in both)}")
    for b in bad:
        print(b)
    print(f"results: {os.path.join(args.out, 'results.tsv')}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
